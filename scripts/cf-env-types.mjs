#!/usr/bin/env node
/**
 * The Worker env type, generated from wrangler.toml (#387).
 *
 * `cloudflare-env.d.ts` is committed, and this script is the only thing that
 * writes it: `npm run cf-typegen` regenerates it, `npm run cf-typegen:check`
 * is the drift gate. The committed file is therefore not a copy of raw
 * `wrangler types` output -- two normalizations below make it both smaller and
 * machine-independent. Both are applied by this script so the file and the gate
 * can never disagree about what "generated" means.
 *
 * Usage: node scripts/cf-env-types.mjs [--check]
 *
 * Why this script and not `wrangler types --check` — that flag is not a gate on
 * the committed file. Verified on wrangler 4.149.0:
 *
 * 1. It compares the `hash:` in the header comment and never the body, at every
 *    spelling. Hand-edit the committed file -- `ORDERS_DB: D1Database` to
 *    `R2Bucket`, the exact typo this issue exists to catch, or delete the
 *    reference line added below -- and it still exits 0 and prints "up to date".
 * 2. That hash digests the *invocation* as well as the config, so a check is
 *    meaningful only spelled exactly like the generation it checks.
 *    `wrangler types --check cloudflare-env.d.ts` omits `--env-interface`, so it
 *    expects an interface named `Env` where the file records `CloudflareEnv`, and
 *    exits 1 on a file that is exactly right. (`--include-runtime=false` does not
 *    enter the hash; `--env-interface` does.)
 *
 * Item 1 is the disqualifying one; item 2 is why the spelling has to be kept in
 * step by hand if anyone ever does reach for the built-in.
 *
 * A normalized file is by definition not byte-identical to wrangler's output, so
 * --check can be neither the gate nor a check on the body, and `normalize()`
 * below has to own both sides for the comparison to mean anything.
 */

import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Repo-relative on purpose: the spelling reaches the generated `hash:` header. */
const TARGET = "cloudflare-env.d.ts";

/**
 * The exact argv, not a paraphrase of it.
 *
 * Wrangler folds the invocation *and* the config into the `hash:` it writes into
 * line 2, so a gate that ran a differently-spelled command would red on an
 * unchanged wrangler.toml. `--include-runtime=false` drops the ~600KB of
 * inlined workerd runtime types; the package that ships them is already a
 * devDependency, and the trimmed file says so itself (WORKERS_TYPES_REFERENCE).
 */
const WRANGLER_ARGS = [
  "types",
  "--env-interface",
  "CloudflareEnv",
  "--include-runtime=false",
  TARGET,
];

/**
 * `--include-runtime=false` also drops the declarations of the four binding
 * types the interface names, so the trimmed file alone is TS2304 on R2Bucket,
 * D1Database, RateLimit and Fetcher. This is where it gets them back from the
 * package. `skipLibCheck` is what makes the package-vs-lib.dom clashes between
 * the two invisible; nothing here needs them resolved.
 */
const WORKERS_TYPES_REFERENCE = [
  '/// <reference types="@cloudflare/workers-types" />',
  "//",
  "// Generated by scripts/cf-env-types.mjs, which normalises wrangler's output in",
  "// three ways: this reference (wrangler's runtime types are not emitted, and the",
  "// package is), the removal of `Cloudflare.GlobalProps`, whose",
  "// `typeof import(\"./worker\")` pulls in the worker.ts that tsconfig excludes --",
  "// its only import, `.open-next/worker.js`, is a build artifact -- and the",
  "// removal of the `NodeJS.ProcessEnv` augmentation, which describes a Worker",
  "// var and is wrong about a Node one. Edit the script, never this file.",
  "// Regenerate with `npm run cf-typegen`.",
].join("\n");

/**
 * The whole normalization, as one pure function.
 *
 * Idempotent: `normalize(normalize(x)) === normalize(x)`. The gate below relies
 * on it -- it regenerates a file that already went through here once, so a
 * second pass must be a no-op or every run would look like drift.
 */
export function normalize(source) {
  const trimmed = source.replace(/^﻿/, "");
  // Body lines are matched at *two* tabs so the match cannot leave the
  // interface. At one tab the group runs straight past GlobalProps' own closing
  // brace and swallows every sibling interface in the namespace up to the
  // namespace's, which silently drops declarations wrangler emits -- for this
  // repo `[env.staging]`, that is `Cloudflare.StagingEnv`.
  const withoutMainModule = trimmed.replace(
    /\tinterface GlobalProps \{\n(?:\t\t[^\n]*\n)*\t\}\n/u,
    "",
  );
  // Keyed on the *declaration* surviving the strip, not on the word appearing
  // anywhere in the source: the header comment this function prepends names
  // `Cloudflare.GlobalProps`, so keying on the word would throw on the second
  // pass of an already-normalized file and break the idempotence above. A
  // declaration left behind is the real hazard -- its `typeof import("./worker")`
  // is TS2307 on a fresh clone, which is what tsconfig excludes `worker.ts` for.
  if (/\binterface GlobalProps \{/u.test(withoutMainModule)) {
    throw new Error(
      "wrangler's output no longer has the shape this script strips: a " +
        '`interface GlobalProps { ... }` block survived the strip, so its ' +
        '`typeof import("./worker")` would go into the committed file. Re-read ' +
        "wrangler's output and update normalize() before committing it.",
    );
  }
  // `declare namespace NodeJS { interface ProcessEnv ... }`, dropped whole.
  //
  // Wrangler emits it to make a Cloudflare var read as a plain string in
  // `process.env`, which is a Worker fact leaking into a Node global: the
  // interface makes `NEXT_PUBLIC_SITE_URL` *required* and narrows it to the two
  // literal hosts in `[vars]`. Neither is true of `process.env`, where any key
  // may be absent and every value is a string -- and both are load-bearing,
  // because a required key rejects `delete process.env.X` (TS2790) and a
  // literal union rejects assigning any other string (TS2322). Sixteen sites in
  // the test suite hit exactly that; they are only quiet today because
  // `process` is `any` (#401).
  //
  // The whole namespace goes rather than the one line inside it: after the
  // interface is removed the namespace would be empty, and an empty
  // `declare namespace NodeJS {}` is a claim that NodeJS is declared here.
  //
  // `type StringifyValues<...>` is left behind. It is wrangler's own output and
  // now unused -- three lines of dead type in a generated file is a cheaper
  // thing to carry than a third pattern to keep in step, and the next wrangler
  // that uses it elsewhere would be silently broken by stripping it.
  // The closing brace's newline is optional, so the block goes whether or not
  // the source ends right after it (wrangler writes one, a fixture built by
  // joining lines need not) and whatever follows keeps its own line break.
  const withoutProcessEnv = withoutMainModule.replace(
    /^declare namespace NodeJS \{\n(?:\t[^\n]*\n)*\}\n?/mu,
    "",
  );
  if (/\binterface ProcessEnv\b/u.test(withoutProcessEnv)) {
    throw new Error(
      "wrangler's output no longer has the shape this script strips: an " +
        "`interface ProcessEnv` survived, so the committed file would describe " +
        "a Worker var as a required Node one. Re-read wrangler's output and " +
        "update normalize() before committing it.",
    );
  }
  const body = withoutProcessEnv.startsWith(WORKERS_TYPES_REFERENCE)
    ? withoutProcessEnv
    : `${WORKERS_TYPES_REFERENCE}\n${withoutProcessEnv}`;
  // Wrangler writes no trailing newline; git would then report every file as
  // changed on the last line.
  return `${body.trimEnd()}\n`;
}

function wranglerBinary() {
  const local = join(root, "node_modules", ".bin", "wrangler");
  if (!existsSync(local)) {
    throw new Error(`no wrangler at ${local} -- run npm install first`);
  }
  return local;
}

function generate() {
  const run = spawnSync(wranglerBinary(), WRANGLER_ARGS, {
    cwd: root,
    stdio: "inherit",
  });
  if (run.status !== 0) {
    throw new Error(`wrangler types exited ${run.status}`);
  }
}

/**
 * Regenerate, then write `normalize()` over the result — in that order. Wrangler
 * truncates the target before it writes, so what it just produced is the only
 * input there is; normalizing anything read beforehand would be discarded.
 */
function regenerate() {
  generate();
  writeFileSync(join(root, TARGET), normalize(readFileSync(join(root, TARGET), "utf8")));
}

/**
 * `import.meta.main`, not an unconditional top level: `normalize()` is exported
 * so `tests/cf-env-types.test.mts` can drive it against fixtures, and importing
 * this module for that must not shell out to wrangler and rewrite a committed
 * file as a side effect of loading a test.
 */
if (import.meta.main) {
  const check = process.argv.includes("--check");
  const absolute = join(root, TARGET);
  const before = existsSync(absolute) ? readFileSync(absolute, "utf8") : null;

  regenerate();

  if (!check) {
    console.log(`wrote ${TARGET}`);
  } else if (before === readFileSync(absolute, "utf8")) {
    console.log(`${TARGET} matches wrangler.toml`);
  } else {
    // Put the committed file back: a check that leaves the tree rewritten cannot
    // be run on a dirty checkout, which is exactly where its verdict matters.
    if (before === null) rmSync(absolute);
    else writeFileSync(absolute, before);
    console.error(
      `${TARGET} is out of date with wrangler.toml.\n` +
        "Run `npm run cf-typegen` and commit the result.",
    );
    process.exit(1);
  }
}
